export function permissionsForRole(role: MembershipRole): Permission[] {
  return ROLE_PERMISSIONS[role]
}

export function tabsForPermissions(permissions: string[]): string[] {
  const tabs = new Set<string>(['Dashboard'])
  for (const permission of permissions) {
    const mapped = PERMISSION_TABS[permission as Permission]
    if (mapped) {
      for (const tab of mapped) tabs.add(tab)
    }
  }
  return [...tabs].sort()
}
